#!/usr/bin/env node
// Regenerates src/moveAbortCatalog.generated.ts from the Move contract sources.
//
//   node scripts/generate-error-codes.mjs [--contracts <path>] [--armature <path>]
//     [--armature-vault <path>] [--armature-trading <path>] [--check]
//
// The contracts live in separate repositories: trinary-exchange (triex + the
// CRED token) and the three Armature repos, whose aborts the organization
// flows surface. Point each flag (or env var) at a checkout. Every repository
// is required, so a missing checkout fails loudly instead of quietly shrinking
// the catalog. The generated catalog is committed, so building and testing the
// SDK never needs these checkouts — only regenerating does.
//
//   --contracts <trinary-exchange>   $TRIEX_CONTRACTS             (default ../trinary-exchange)
//   --armature <armature>            $ARMATURE_CONTRACTS          (default ../armature)
//   --armature-vault <repo>          $ARMATURE_VAULT_CONTRACTS    (default ../armature-vault)
//   --armature-trading <repo>        $ARMATURE_TRADING_CONTRACTS  (default ../armature-trading)
//
// Module names are the catalog key, so the packages must not declare abort
// codes in same-named modules; a clash is reported as a duplicate code.

import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { buildCatalog } from './parse-move-errors.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const SDK_ROOT = join(HERE, '..')
const OUT = join(SDK_ROOT, 'src', 'moveAbortCatalog.generated.ts')

function arg(flag) {
  const i = process.argv.indexOf(flag)
  return i === -1 ? null : process.argv[i + 1]
}

const REPOS = [
  {
    label: 'trinary-exchange',
    flag: '--contracts',
    env: 'TRIEX_CONTRACTS',
    dirs: ['packages/triex/sources', 'packages/token/sources'],
  },
  {
    label: 'armature',
    flag: '--armature',
    env: 'ARMATURE_CONTRACTS',
    dirs: ['packages/armature_framework/sources', 'packages/armature_proposals/sources'],
  },
  {
    label: 'armature-vault',
    flag: '--armature-vault',
    env: 'ARMATURE_VAULT_CONTRACTS',
    dirs: ['packages/armature_vault/sources'],
  },
  {
    label: 'armature-trading',
    flag: '--armature-trading',
    env: 'ARMATURE_TRADING_CONTRACTS',
    dirs: ['packages/armature_trading/sources'],
  },
]

const sourceRoots = REPOS.flatMap(repo => {
  const repoRoot = resolve(arg(repo.flag) ?? process.env[repo.env] ?? join(SDK_ROOT, '..', repo.label))
  return repo.dirs.map(d => ({ dir: join(repoRoot, d), repoRoot, label: repo.label, flag: repo.flag, env: repo.env }))
})

for (const root of sourceRoots) {
  if (!existsSync(root.dir)) {
    console.error(`No Move sources at ${root.dir}`)
    console.error(`Pass ${root.flag} <path to the ${root.label} checkout> or set $${root.env}.`)
    process.exit(2)
  }
}

const catalog = buildCatalog(sourceRoots)

// Failure modes a hand-maintained table drifts into; catching them here is the
// reason this file is generated rather than written by hand.
const problems = []
for (const c of catalog.collisions) {
  problems.push(`duplicate code ${c.code} in module '${c.module}': ${c.names.join(' and ')}`)
}
for (const e of catalog.unkeyed) {
  problems.push(`${e.file}:${e.line} ${e.module}::${e.name} has no stable code — add #[error(code = N)]`)
}
const modulesWithBareErrors = new Set(catalog.unkeyed.map(e => e.module))
for (const e of catalog.entries) {
  // A clever error with code 0 is indistinguishable from an un-annotated
  // #[error] — but only when the same module has one. Where every error in the
  // module carries an explicit code (armature_vault's ou_receipt_vault), an
  // explicit-code-0 abort can only be that constant, and the runtime lookup
  // falls back to it.
  if (e.clever && e.code === 0 && modulesWithBareErrors.has(e.module)) {
    problems.push(`${e.file}:${e.line} ${e.module}::${e.name} uses #[error(code = 0)]; 0 is reserved as "unset"`)
  }
}

const byModule = Object.fromEntries(
  Object.entries(catalog.byModule).map(([module, table]) => [
    module,
    Object.fromEntries(
      Object.entries(table).map(([code, e]) => [
        code,
        { name: e.name, label: e.label, message: e.message, clever: e.clever, source: `${e.file}:${e.line}` },
      ]),
    ),
  ]),
)

const names = catalog.entries.map(e => `  | '${e.module}::${e.name}'`).join('\n')
const body = `// Generated by scripts/generate-error-codes.mjs — do not edit by hand.
// Sources: ${sourceRoots.map(r => `${r.label}/${r.dir.replace(r.repoRoot + '/', '')}`).join(', ')}
// Regenerate: npm run generate:error-codes

/** Every abort constant declared by the contracts, as \`module::EConstantName\`. */
export type MoveAbortName =
${names}

export interface MoveAbortEntry {
  /** The Move constant's name, e.g. \`EInvalidFee\`. */
  name: string
  /** Label derived from the constant's doc comment, or from its name. */
  label: string
  /** The \`#[error]\` message string, when the constant declares one. */
  message: string | null
  /** Whether the constant is a clever error (\`#[error(code = N)]\`). */
  clever: boolean
  /** Where the constant is declared, for debugging. */
  source: string
}

/** Abort entries keyed by module name, then by abort code. */
export const MOVE_ABORT_CATALOG: Record<
  string,
  Record<number, MoveAbortEntry>
> = ${JSON.stringify(byModule, null, 2)}
`

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== body) {
    console.error(`stale: ${OUT}`)
    console.error('Run: npm run generate:error-codes')
    process.exit(1)
  }
  console.error('error-codes catalog is up to date')
} else {
  writeFileSync(OUT, body)
  console.error(`wrote ${OUT.replace(SDK_ROOT + '/', '')}`)
}

console.error(`${catalog.entries.length} abort constants across ${Object.keys(catalog.byModule).length} modules`)

if (problems.length > 0) {
  console.error('\nproblems:')
  for (const p of problems) console.error(`  ${p}`)
  process.exit(1)
}

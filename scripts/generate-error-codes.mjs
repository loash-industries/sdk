#!/usr/bin/env node
// Regenerates src/moveAbortCatalog.generated.ts from the Move contract sources.
//
//   node scripts/generate-error-codes.mjs [--contracts <path>] [--check]
//
// The contracts live in a separate repository (loash-industries/trinary-exchange).
// Point --contracts at a checkout of it, or set $TRIEX_CONTRACTS. The generated
// catalog is committed, so building and testing the SDK never needs that checkout —
// only regenerating does.

import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { buildCatalog } from './parse-move-errors.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const SDK_ROOT = join(HERE, '..')
const OUT = join(SDK_ROOT, 'src', 'moveAbortCatalog.generated.ts')

function arg(flag) {
  const i = process.argv.indexOf(flag)
  return i === -1 ? null : process.argv[i + 1]
}

const contracts = resolve(
  arg('--contracts') ?? process.env.TRIEX_CONTRACTS ?? join(SDK_ROOT, '..', 'trinary-exchange'),
)
const sourceRoots = ['packages/triex/sources', 'packages/token/sources'].map(r => join(contracts, r))

for (const root of sourceRoots) {
  if (!existsSync(root)) {
    console.error(`No Move sources at ${root}`)
    console.error('Pass --contracts <path to trinary-exchange checkout> or set $TRIEX_CONTRACTS.')
    process.exit(2)
  }
}

const catalog = buildCatalog(sourceRoots, contracts)

// Failure modes a hand-maintained table drifts into; catching them here is the
// reason this file is generated rather than written by hand.
const problems = []
for (const c of catalog.collisions) {
  problems.push(`duplicate code ${c.code} in module '${c.module}': ${c.names.join(' and ')}`)
}
for (const e of catalog.unkeyed) {
  problems.push(`${e.file}:${e.line} ${e.module}::${e.name} has no stable code — add #[error(code = N)]`)
}
for (const e of catalog.entries) {
  // A clever error with code 0 is indistinguishable from an un-annotated #[error].
  if (e.clever && e.code === 0) {
    problems.push(`${e.file}:${e.line} ${e.module}::${e.name} uses #[error(code = 0)]; 0 is reserved as "unset"`)
  }
}

const byModule = Object.fromEntries(
  Object.entries(catalog.byModule).map(([module, table]) => [
    module,
    Object.fromEntries(
      Object.entries(table).map(([code, e]) => [
        code,
        { name: e.name, label: e.label, message: e.message, clever: e.clever, source: `${e.file}:${e.line}` },
      ]),
    ),
  ]),
)

const names = catalog.entries.map(e => `  | '${e.module}::${e.name}'`).join('\n')
const body = `// Generated by scripts/generate-error-codes.mjs — do not edit by hand.
// Source: loash-industries/trinary-exchange @ ${sourceRoots.map(r => r.replace(contracts + '/', '')).join(', ')}
// Regenerate: npm run generate:error-codes

/** Every abort constant declared by the contracts, as \`module::EConstantName\`. */
export type MoveAbortName =
${names}

export interface MoveAbortEntry {
  /** The Move constant's name, e.g. \`EInvalidFee\`. */
  name: string
  /** Label derived from the constant's doc comment, or from its name. */
  label: string
  /** The \`#[error]\` message string, when the constant declares one. */
  message: string | null
  /** Whether the constant is a clever error (\`#[error(code = N)]\`). */
  clever: boolean
  /** Where the constant is declared, for debugging. */
  source: string
}

/** Abort entries keyed by module name, then by abort code. */
export const MOVE_ABORT_CATALOG: Record<
  string,
  Record<number, MoveAbortEntry>
> = ${JSON.stringify(byModule, null, 2)}
`

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== body) {
    console.error(`stale: ${OUT}`)
    console.error('Run: npm run generate:error-codes')
    process.exit(1)
  }
  console.error('error-codes catalog is up to date')
} else {
  writeFileSync(OUT, body)
  console.error(`wrote ${OUT.replace(SDK_ROOT + '/', '')}`)
}

console.error(`${catalog.entries.length} abort constants across ${Object.keys(catalog.byModule).length} modules`)

if (problems.length > 0) {
  console.error('\nproblems:')
  for (const p of problems) console.error(`  ${p}`)
  process.exit(1)
}
